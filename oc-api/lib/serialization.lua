---@meta

---The serialization library (`require("serialization")`): converts values to strings of Lua code and back,
---e.g. to save them to files or send them over the network.
---@class serializationlib
local serialization = {}

---Converts a value into a string of Lua code that `serialization.unserialize` turns back into the value.
---Supports nil, booleans, numbers (including NaN and infinity), strings and tables without cycles;
---other types (functions, userdata) and cycles raise an error unless `pretty` is set.
---`pretty` produces human-readable output for display, which usually cannot be unserialized:
---`true` shows at most 10 lines, a number at most that many lines.
---@param value any
---@param pretty? boolean|number
---@return string
function serialization.serialize(value, pretty) end

---Restores a value from a string generated by `serialization.serialize`.
---Returns `nil` and an error message if the string cannot be loaded.
---@param data string
---@return any value
---@return string? reason
function serialization.unserialize(data) end

return serialization
